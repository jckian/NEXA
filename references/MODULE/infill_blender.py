# ----------------------------------------------------------------------------
# Parsing
# ----------------------------------------------------------------------------
def parse_verts(s):
    out = []
    for tok in s.strip().strip("|").split("|"):
        if not tok:
            continue
        x, y, z = tok.split(",")
        out.append((float(x) * SCALE, float(y) * SCALE, float(z) * SCALE))
    return out


def parse_faces(s):
    out = []
    for tok in s.strip().strip("|").split("|"):
        if not tok:
            continue
        out.append(tuple(int(i) for i in tok.split(",")))
    return out


# ----------------------------------------------------------------------------
# Blender helpers
# ----------------------------------------------------------------------------
def get_material():
    mat = bpy.data.materials.get("1_@01_mat")
    if mat is None:
        mat = bpy.data.materials.new("1_@01_mat")
        mat.use_nodes = True
        bsdf = mat.node_tree.nodes.get("Principled BSDF")
        if bsdf is not None:
            bsdf.inputs["Base Color"].default_value = (*MODULE_COLOR, 1.0)
        mat.diffuse_color = (*MODULE_COLOR, 1.0)   # viewport solid colour
    return mat


def get_collection():
    coll = bpy.data.collections.get(MODULE_NAME)
    if coll is None:
        coll = bpy.data.collections.new(MODULE_NAME)
        bpy.context.scene.collection.children.link(coll)
    return coll


def clean_mesh(obj):
    """Weld coincident verts and merge coplanar triangles into clean n-gons."""
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=MERGE_DIST)
    bmesh.ops.dissolve_limit(
        bm,
        angle_limit=DISSOLVE_ANGLE,
        use_dissolve_boundaries=False,
        verts=bm.verts,
        edges=bm.edges,
    )
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.to_mesh(obj.data)
    bm.free()
    obj.data.update()


def build_part(part, mat, coll, parent):
    verts = parse_verts(part["v"])
    faces = parse_faces(part["f"])
    assert len(verts) == part["nv"], "%s: vert count %d != %d" % (
        part["name"], len(verts), part["nv"])
    assert len(faces) == part["nf"], "%s: face count %d != %d" % (
        part["name"], len(faces), part["nf"])

    me = bpy.data.meshes.new(part["name"])
    me.from_pydata(verts, [], faces)
    me.validate(verbose=False)

    ob = bpy.data.objects.new(part["name"], me)
    coll.objects.link(ob)
    ob.parent = parent
    if ob.data.materials:
        ob.data.materials[0] = mat
    else:
        ob.data.materials.append(mat)

    clean_mesh(ob)
    return ob


def main():
    coll = get_collection()
    mat = get_material()

    root = bpy.data.objects.new(MODULE_NAME + "_root", None)   # empty as parent
    root.empty_display_type = "PLAIN_AXES"
    root.empty_display_size = 50.0 * SCALE
    coll.objects.link(root)

    built = [build_part(p, mat, coll, root) for p in PARTS]

    print("Built block '%s' -> %d parts:" % (MODULE_NAME, len(built)))
    for ob in built:
        print("   %-8s verts=%4d  faces=%4d"
              % (ob.name, len(ob.data.vertices), len(ob.data.polygons)))


if __name__ == "__main__":
    main()
